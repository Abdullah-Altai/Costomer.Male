    <div class="card-actions">${b.status === "pending" ? `<button onclick="cancelBooking('${b.id}')">${tr("canceled")}</button>` : `<button onclick="repeatBooking('${b.id}')">${tr("booking")}</button>`}${b.status === "completed" ? `<button onclick="openReview('${b.id}')">${tr("rating")}</button>` : `<button onclick="completeDemo('${b.id}')">${tr("completed")}</button>`}</div>
