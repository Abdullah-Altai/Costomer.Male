function isBooked(shopId, barberId, date, time){ return bookings.some(b => b.shopId === shopId && b.barberId === barberId && b.date === date && b.time === time && b.status !== "canceled"); }
function updateTimes(){
  const shopId = $("#shopSelect").value;
  const barberId = $("#barberSelect").value;
  const date = $("#bookingDate").value;
  const oldValue = $("#bookingTime").value;

  $("#bookingTime").innerHTML = times.map(t => {
    const booked = isBooked(shopId, barberId, date, t);
    return `<option value="${t}" ${booked ? "disabled" : ""}>${t}${booked ? " - " + tr("booked") : ""}</option>`;
  }).join("");

  const oldOption = Array.from($("#bookingTime").options).find(o => o.value === oldValue && !o.disabled);
  if(oldOption){
    $("#bookingTime").value = oldValue;
  }else{
    const firstFree = Array.from($("#bookingTime").options).find(o => !o.disabled);
    if(firstFree) $("#bookingTime").value = firstFree.value;
  }
}
